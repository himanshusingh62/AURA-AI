@pytest.fixture
def mock_genai_client():
    """Create a mock genai.Client with simulated embedding and content generation."""
    client = MagicMock()

    # Mock embed_content to return 3,072-dimensional zero vectors with an indicator value
    def fake_embed(model, contents, **kwargs):
        if isinstance(contents, list):
            count = len(contents)
        else:
            count = 1
        fake_embs = []
        for i in range(count):
            emb = MagicMock()
            # 3,072 dims
            emb.values = [0.05 * (i + 1)] * 3072
            fake_embs.append(emb)
        resp = MagicMock()
        resp.embeddings = fake_embs
        return resp

    client.models.embed_content.side_effect = fake_embed

    # Mock generate_content to return structured answers
    fake_response = MagicMock()
    fake_response.text = "This is a grounded answer generated by the mocked Google Gen AI Gemini model."
    client.models.generate_content.return_value = fake_response

    return client


