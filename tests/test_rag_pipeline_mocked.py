def test_query_multimodal_modes_mocked(mock_genai_client):
    with patch("backend.embeddings.get_genai_client", return_value=mock_genai_client), \
         patch("backend.query_engine.get_genai_client", return_value=mock_genai_client), \
         patch("backend.multimodal_engine.get_genai_client", return_value=mock_genai_client):

        # Mode 1: No files loaded
        res_none = query_multimodal("Hello", pdf_index=None, images=[])
        assert res_none.query_mode == "none"

        # Mode 2: Image-only query
        dummy_pil = Image.new("RGB", (100, 100), color="purple")
        proc_img = ProcessedImage(
            filename="diagram.png",
            format="PNG",
            width=100,
            height=100,
            mode="RGB",
            size_mb=0.1,
            thumbnail_base64="data:image/png;base64,fake",
            raw_bytes=b"fake",
            pil_image=dummy_pil,
        )
        res_img = query_multimodal("What is this diagram?", pdf_index=None, images=[proc_img], api_key="AIzaSyMockKey12345")
        assert res_img.query_mode == "image_only"
        assert len(res_img.image_sources) == 1
        assert res_img.image_sources[0]["filename"] == "diagram.png"

        # Mode 3: Combined PDF + Image
        docs = [Document(text="Neural architecture design notes.", metadata={"page_number": 1, "source": "notes.pdf"})]
        pdf_index = build_index(docs, api_key="AIzaSyMockKey12345")

        res_comb = query_multimodal(
            question="Compare the architecture notes with the diagram",
            pdf_index=pdf_index,
            images=[proc_img],
            api_key="AIzaSyMockKey12345",
        )
        assert res_comb.query_mode == "combined"
        assert len(res_comb.pdf_sources) >= 1
        assert len(res_comb.image_sources) == 1
