def test_build_index_and_multi_document_indexing(mock_genai_client):
    with patch("backend.embeddings.get_genai_client", return_value=mock_genai_client):
        # 1. Index first PDF
        doc1_pages = [
            Document(text="Document 1 Section A", metadata={"page_number": 1, "source": "doc1.pdf"}),
            Document(text="Document 1 Section B", metadata={"page_number": 2, "source": "doc1.pdf"}),
        ]
        index = build_index(doc1_pages, api_key="AIzaSyMockKey12345")
        initial_chunks = len(index.docstore.docs)
        assert initial_chunks >= 2

        # 2. Append second PDF to the same unified vector store
        doc2_pages = [
            Document(text="Document 2 Section Alpha", metadata={"page_number": 1, "source": "doc2.pdf"}),
        ]
        updated_index = build_index(doc2_pages, api_key="AIzaSyMockKey12345", existing_index=index)
        assert len(updated_index.docstore.docs) > initial_chunks


